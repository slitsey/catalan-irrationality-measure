"""Generate the kernel-checked certificate for a kappa = 2 trial pair.

Writes a directory of Lean files:
  Data.lean      trial data, derivative quotients, plans, bounds
  AQ.lean        the derivative quotients equal the computed fractions
  ChecksX<k>.lean, ChecksY<k>.lean   one theorem per piece (separate kernel checks)
  Norms.lean     the two weighted norms
  Sup.lean       sup X <= MX, sup Y <= MY, norms, and the dual constant
The column field includes log(1+s).
Usage: gen_weighted_dual.py trial.json outdir Namespace [module]
"""
import json, os, sys, time, math
from fractions import Fraction as F
import numpy as np
from fields import *
from polyq import *
from isolate import plan
from emit import *

CHUNK = 18


def lean_header(module, imports):
    if module:
        return "module\n\n" + "".join(f"public import {i}\n" for i in imports) + \
            "\n@[expose] public section\n\n"
    return "".join(f"import {i}\n" for i in imports) + "\n"


def piece(p):
    lo, hi, k = p
    return f"({q(lo)}, {q(hi)}, {'true' if k == 'bracket' else 'false'})"


def norm_closed(u):
    """Float value of sum u_k^2/k via the closed form."""
    K = len(u.cs)
    tot = 0.0
    for k in range(1, K + 1):
        f = u.cs[k - 1] / E8
        t = sum((complex(rr, ri) * complex(zr, zi) ** k).real for zr, zi, rr, ri in u.tail)
        tot += (f * f + 2 * f * t) / k
    pair = 0j
    for a in u.tail:
        za, ra = complex(a[0], a[1]), complex(a[2], a[3])
        for b in u.tail:
            zb, rb = complex(b[0], b[1]), complex(b[2], b[3])
            pair += -ra * rb / 2 * np.log(1 - za * zb) - ra * rb.conjugate() / 2 * np.log(1 - za * zb.conjugate())
    return tot + pair.real


def modified_Y_field(V, s):
    return Y_field(V, s) + np.log1p(s)


def main(trial_json, outdir, ns, module=False):
    os.makedirs(outdir, exist_ok=True)
    d = json.load(open(trial_json))
    P = Trial.from_json(d['P']); V = Trial.from_json(d['V'])
    AX, QX = frac_sum(row_fracs(P, V)); AY, QY = frac_sum(col_fracs(V) + [([F(1)], [F(1), F(1)])])
    t = time.time()
    px = plan(AX, F(-1), F(1), excluded=(F(0),))
    py = plan(AY, F(0), F(1), excluded=())
    print('plans', len(px), len(py), f'{time.time() - t:.0f}s', flush=True)
    MX = X_field(P, V, np.array([-1.0]))[0]
    for lo, hi, k in px:
        if k == 'bracket':
            MX = max(MX, X_field(P, V, np.array([float(lo)]))[0] + float((hi - lo) * ratio_bound(AX, QX, lo, hi - lo)))
    MY = -1e9
    for lo, hi, k in py:
        if k == 'bracket':
            MY = max(MY, modified_Y_field(V, np.array([float(lo)]))[0] + float((hi - lo) * ratio_bound(AY, QY, lo, hi - lo)))
    MXq = F(-9498627, 10**7)
    MYq = F(-12145624, 10**7)
    NP = norm_closed(P); NV = norm_closed(V)
    NPq = F(713397, 10**7)
    NVq = F(13114478, 10**7)
    L2lo = F(6931471803, 10**10)
    Ucert = -(-F(11, 16) * L2lo + 2 * NPq + NVq / 2 + MXq + MYq)
    Uq = F(math.floor((Ucert - F(1, 10**9)) * 10**8), 10**8)
    print('MX', float(MXq), 'MY', float(MYq), 'NP', float(NPq), 'NV', float(NVq), 'U', float(Uq), flush=True)
    base = f"CatalanMeasure.{ns}"
    # Data
    src = lean_header(module, ["CatalanMeasure.Cert.ModColumn", "CatalanMeasure.Cert.Norm"])
    src += f"""/-! Certificate data for the modified second energy dual (`κ = 2`, column field plus `log(1+s)`) with trial
sequences.  Generated by `scripts/certgen/gen_weighted_dual.py` from `scripts/certgen/weighted_trial.json`. -/

namespace {base}

open CatalanMeasure.Cert

def Pc : List ℤ := {intlist(P.cs)}
def Vc : List ℤ := {intlist(V.cs)}
def P : List TailQ := {tails(P.tail)}
def V : List TailQ := {tails(V.tail)}
def AX : List ℚ := {qlist(AX, 1)}
def QX : List ℚ := {qlist(QX, 1)}
def AY : List ℚ := {qlist(AY, 1)}
def QY : List ℚ := {qlist(QY, 1)}
def MX : ℚ := {q(MXq)}
def MY : ℚ := {q(MYq)}
def NP : ℚ := {q(NPq)}
def NV : ℚ := {q(NVq)}
def planX : List Piece := [{(','+chr(10)+'  ').join(piece(p) for p in px)}]
def planY : List Piece := [{(','+chr(10)+'  ').join(piece(p) for p in py)}]

def okX (p : Piece) : Bool := gapOK AX p && rowBracketOK Pc Vc P V AX QX MX p
def okY (p : Piece) : Bool := gapOK AY p && modColBracketOK Vc V AY QY MY p

end {base}
"""
    open(os.path.join(outdir, 'Data.lean'), 'w').write(src)
    # AQ
    src = lean_header(module, [f"{base}.Data"])
    src += f"""namespace {base}

open CatalanMeasure.Cert

set_option maxRecDepth 1000000 in
theorem hAQX : fracSum (rowFracs Pc Vc P V) = (AX, QX) := by decide +kernel

set_option maxRecDepth 1000000 in
theorem hAQY : fracSum (modColFracs Vc V) = (AY, QY) := by decide +kernel

set_option maxRecDepth 1000000 in
theorem hchainX : rowCheck P V AX planX = true := by decide +kernel

set_option maxRecDepth 1000000 in
theorem hchainY : colCheck V AY planY = true := by decide +kernel

set_option maxRecDepth 1000000 in
theorem hendX : rowEndOK Pc Vc P V MX = true := by decide +kernel

end {base}
"""
    open(os.path.join(outdir, 'AQ.lean'), 'w').write(src)
    # chunks
    chunks = []
    for tag, pl in (('X', px), ('Y', py)):
        for c in range(0, len(pl), CHUNK):
            name = f"Checks{tag}{c // CHUNK}"
            chunks.append(name)
            src = lean_header(module, [f"{base}.Data"])
            src += f"namespace {base}\n\nopen CatalanMeasure.Cert\n\n"
            for i in range(c, min(c + CHUNK, len(pl))):
                src += f"""set_option maxRecDepth 1000000 in
theorem ok{tag}_{i} : ok{tag} {piece(pl[i])} = true := by decide +kernel

"""
            src += f"end {base}\n"
            open(os.path.join(outdir, name + '.lean'), 'w').write(src)
    # Norms
    src = lean_header(module, [f"{base}.Data"])
    src += f"""namespace {base}

open CatalanMeasure.Cert

set_option maxRecDepth 1000000 in
theorem hNP : normOK Pc P NP = true := by decide +kernel

set_option maxRecDepth 1000000 in
theorem hNV : normOK Vc V NV = true := by decide +kernel

end {base}
"""
    open(os.path.join(outdir, 'Norms.lean'), 'w').write(src)
    # Sup
    imps = [f"{base}.AQ", f"{base}.Norms"] + [f"{base}.{c}" for c in chunks]
    src = lean_header(module, imps)
    xs = ", ".join(f"okX_{i}" for i in range(len(px)))
    ys = ", ".join(f"okY_{i}" for i in range(len(py)))
    src += f"""namespace {base}

open CatalanMeasure.Cert OAI.InternalCatalan

theorem allX : planX.all okX = true := by
  simp only [planX, List.all_cons, List.all_nil, {xs}, Bool.and_true]

theorem allY : planY.all okY = true := by
  simp only [planY, List.all_cons, List.all_nil, {ys}, Bool.and_true]

theorem row_sup : ∀ x ∈ Set.Ico (-1 : ℝ) 0 ∪ Set.Ioo 0 1,
    realEnergyRowTrialField 2 0 (trialSeq Pc P) (trialSeq Vc V) x ≤ (MX : ℝ) :=
  rowCheck_spec hAQX hchainX (all_and_left (f := gapOK AX) (g := rowBracketOK Pc Vc P V AX QX MX) allX)
    (all_and_right (f := gapOK AX) (g := rowBracketOK Pc Vc P V AX QX MX) allX) hendX

theorem col_sup : ∀ x ∈ Set.Ioo (0 : ℝ) 1, modColField (trialSeq Vc V) x ≤ (MY : ℝ) :=
  modColCheck_spec hAQY hchainY (all_and_left (f := gapOK AY) (g := modColBracketOK Vc V AY QY MY) allY)
    (all_and_right (f := gapOK AY) (g := modColBracketOK Vc V AY QY MY) allY)

theorem normP_le : barrierTrialNormSq (trialSeq Pc P) ≤ (NP : ℝ) := normOK_spec hNP
theorem normV_le : barrierTrialNormSq (trialSeq Vc V) ≤ (NV : ℝ) := normOK_spec hNV

theorem MX_eq : (MX : ℝ) = {q(MXq).replace(' : ℚ', ' : ℝ')} := by norm_num [MX]
theorem MY_eq : (MY : ℝ) = {q(MYq).replace(' : ℚ', ' : ℝ')} := by norm_num [MY]
theorem NP_eq : (NP : ℝ) = {q(NPq).replace(' : ℚ', ' : ℝ')} := by norm_num [NP]
theorem NV_eq : (NV : ℝ) = {q(NVq).replace(' : ℚ', ' : ℝ')} := by norm_num [NV]

end {base}
"""
    open(os.path.join(outdir, 'Sup.lean'), 'w').write(src)
    json.dump(dict(MX=str(MXq), MY=str(MYq), NP=str(NPq), NV=str(NVq), U=str(Uq), chunks=chunks),
              open(os.path.join(outdir, 'summary.json'), 'w'), indent=1)
    print('chunks', len(chunks))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3], len(sys.argv) > 4 and sys.argv[4] == 'module')
