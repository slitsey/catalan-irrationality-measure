    C.write('Env.lean', env + FOOT)
    mfg = ' ' if M is not None else ''
    ok_t = f'cellOk nuC Mopt Rtw eWc ePc Fc Dn'
    # tube blocks
    for e in range(C.nE):
        cs = tube[e]
        blocks = [cs[i:i + BLK_TUBE] for i in range(0, len(cs), BLK_TUBE)]
        names = []
        for bi, blk in enumerate(blocks):
            rel = f'Tube/E{e}B{bi:02d}'
