def q1(q):
    return f'qOfP ({q.numerator}) ({q.denominator})'


def rnest(names):
    out = names[-1]
    for n in reversed(names[:-1]):
        out = f'{n} ++ ({out})'
    return out


def pair(q):
    return [q.numerator, q.denominator]


def tape(ints, per=20):
    toks = [str(x) for x in ints]
    return 'raw_ints% [\n    ' + ',\n    '.join(', '.join(toks[i:i + per]) for i in range(0, len(toks), per)) + ']'


class Ctx:
    def __init__(self, bank, mod, scratch):
        self.bank, self.mod = bank, mod
        self.d = gen_bank.derive(bank)
        self.dir = os.path.join(ROOT, *mod.split('.'))
        self.scratch = scratch or os.path.join(HERE, 'out', bank)
        os.makedirs(self.scratch, exist_ok=True)
        d = self.d
        V = d['poly']['vertices']
        s = d['poly']['tailSlope']
        self.Y = d['sc']['umax']
        L = V[-1]
        self.tmax = (self.Y - L[1]) / s
        tail_end = (L[0] - self.tmax, L[1] + s * self.tmax)
        assert tail_end[1] == self.Y
        self.pts = V + [tail_end]
        self.nE = len(self.pts) - 1
        g = d['geom']
        self.RP = [(dens, lo, hi) for (lo, hi, dens) in g['rows']]
        self.CP = [(dens, lo, hi) for (lo, hi, dens) in g['cols']]
        self.Mq = d['sc']['Mq']
        self.Rn = max([h for (_, _, h) in self.RP + self.CP])
        self.Rc = d['sc']['Rc']
        self.T0 = max(2 * self.Rc, 2 * self.Rn)
        self.F = (self.Mq * self.Rc + self.Mq * self.Rn, self.T0)

    def path(self, rel):
        p = os.path.join(self.dir, rel)
        os.makedirs(os.path.dirname(p), exist_ok=True)
        return p

    def write(self, rel, s):
        open(self.path(rel), 'w', encoding='utf-8', newline='\n').write(s)


