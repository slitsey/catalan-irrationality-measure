# ---------------------------------------------------------------------------------- build
def modules(C):
    mods = {}
    for f in glob.glob(os.path.join(C.dir, '**', '*.lean'), recursive=True):
        rel = os.path.relpath(f, C.dir)[:-5].replace(os.sep, '.')
        txt = open(f, encoding='utf-8').read()
        imps = re.findall(r'^import (\S+)', txt, re.M)
        mods[C.mod + '.' + rel] = [i for i in imps if i.startswith(C.mod + '.')]
    return mods


def cmd_build(C, a):
    mods = modules(C)
    done, lock = set(), threading.Lock()
    pending = dict(mods)
    log = []

    def worker():
        while True:
            with lock:
                ready = [m for m, deps in pending.items() if all(x in done for x in deps)]
                if not pending:
                    return
                if not ready:
                    m = None
                else:
                    m = ready[0]
                    del pending[m]
            if m is None:
                time.sleep(3)
                continue
            r = subprocess.run([PY, '-I', '-X', 'utf8', LANES, 'submit', m, str(8 if m.endswith(('.Check', '.Decay')) else 6 if m.endswith('.Glob') else a.gb)], cwd=ROOT,
                               capture_output=True, text=True)
            ok = r.returncode == 0
            with lock:
                done.add(m)
                log.append((m, ok))
                print(('ok   ' if ok else 'FAIL ') + m, flush=True)
    ts = [threading.Thread(target=worker) for _ in range(a.parallel)]
    [t.start() for t in ts]
    [t.join() for t in ts]
    bad = [m for m, ok in log if not ok]
    print('built', len(log), 'failed', bad)


