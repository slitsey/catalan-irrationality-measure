"""Bank-generic lemma-aware decay-cover generator (lane D, package D17).

    python -I cover.py <command> <Bank> --mod <Lean module prefix> [options]

Banks are the keys of `gen_bank.BANKS` (Fifths, Thirds, Chi3, Lambda, Sev1): the receipt triple
(exact-*.json / hyp-*.json, trial in the exact receipt) is read by `gen_bank.derive`, and the data
modules `CatalanCore.Uniform.Bank.Common.Data.<Bank>.{Data,Frame}` (emitted by gen_bank.py) must be built.

Commands (run in this order; `all` runs env..gen..emit):
  env    write <mod>/Env0.lean (node pieces, polygon, far data, noRay data) -- build it first
  gen    write the Lean generators, run them through lanes.py (cells of every proved kind, pair energies)
  emit   read the generator output, write the Lean data modules (Env, Tube, Line, Cap, Energy, Check, Decay)
  build  build the emitted modules leaf-first through lanes.py (<= 3 at a time)

The cover is lemma-aware: for every tube edge / line / cap the piece endpoints on it are the breakpoints;
next to each, the largest breakpoint cell `bp` (Breakpoint.Cell); in between, the multipole cell `mp`
(FarField.Cell, if the global moments pass), jets of order 5..8, mixed cells, the bank's far rule; cap
cells are constant upper bounds of any kind (the PL chord kind `lin` is decoded and checked by the
library but not produced here).  Every kind except `mp` and `lin` is tried on the pieces with those reversed
whose line the cell crosses beyond their end (tag 5, `CellKind.flip`; WALL, 28 Oct).
Every printed cell passed the library Boolean `kindOk` inside the generator;
the Lean modules re-prove each by `decide +kernel`.
"""
