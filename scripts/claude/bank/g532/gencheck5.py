NL = chr(10)
def aff(f): return '⟨%d, %d, %d⟩' % f
def pts_lean(p): return 'Pt.' + p
def step_lean(s):
    if s[0] == 'hyp': return 'Step.hyp %d' % s[1]
    if s[0] == 'add': return 'Step.add %d %d' % (s[1], s[2])
    if s[0] == 'scale': return 'Step.scale %d %d' % (s[1], s[2])
    if s[0] == 'tighten': return 'Step.tighten %d %d' % (s[1], s[2])
    if s[0] == 'const': return 'Step.const %d' % s[1]
    raise ValueError(s)
def zone_lean(z):
    a, b, g, i, g2, eps, kill = z
    return '{ lo := %s, hi := %s, g := %d, i := %d, g2 := %d, eps := [%s], kill := [%s] }' % (
        aff(a), aff(b), g, i, g2, ', '.join(str(x) for x in eps), ', '.join(str(x) for x in kill))

def verify_cert(win, entries):
    for f, prog in entries:
        ds = []
        for st in prog:
            if st[0] == 'hyp': g = win[st[1]]
            elif st[0] == 'add': g = aadd(ds[st[1]], ds[st[2]])
            elif st[0] == 'scale': g = ascl(st[1], ds[st[2]])
            elif st[0] == 'tighten':
                f0 = ds[st[2]]; d = st[1]
                assert d > 0 and f0[0] % d == 0 and f0[1] % d == 0, (f, prog)
                g = (f0[0] // d, f0[1] // d, f0[2] // d)
            elif st[0] == 'const': g = (0, 0, st[1])
            ds.append(g)
        assert any(x[0] == f[0] and x[1] == f[1] and x[2] <= f[2] for x in ds), ('cert does not derive', f, prog)

def emit(key, out):
    parts = split_check(key)
    K = len(parts)
    g0, res0 = parts[0]
    P = g0.P
    for g, res in parts:
        assert g.kind in SUPPORTED, ('unsupported kind', g.kind)
        assert all(res.get(k) for k in ('basic', 'geom', 'hdom', 'graph')), res
        assert getattr(g, 'regs', None) is not None and g.cov is not None, res
    for g, res in parts: verify_cert(g.M.win, g.M.cert.entries)
    nm = P.nm
    L = []
    A = L.append
    A('module')
    A('public import CatalanMeasure.GenD.Uniform.Bank532.Pk.%s' % nm)
    A('public import CatalanMeasure.GenD.Uniform.W.Charts6.Check.Host')
    A('@[expose] public section')
    A('set_option Elab.async false')
    A('set_option maxRecDepth 100000')
    A('')
    A('/-! Generated by scripts/claude/bank/g532/gencheck5.py for %s: the packet data for `checkHost`, the kernel check and the physical host. -/' % key)
    A('namespace CatalanMeasure.GenD.Uniform.Bank532.Pk.%s' % nm)
    A('open CatalanMeasure.GenD.Uniform.W.Charts6.Check')
    A('noncomputable section')
    A('')
    for k, (g, res) in enumerate(parts):
        P = g.P
        cov = g.cov
        A('def pdMeta%d : Meta where' % k)
        A('  b := %d' % P.b)
        A('  ex := %d' % P.ex)
        A('  k0 := %d' % P.k0)
        A('  high := %s' % ('true' if P.high else 'false'))
        A('  vlow := %s' % ('true' if P.vlow else 'false'))
        A('  win := (%s)' % ', '.join(str(x) for x in P.winp))
        A('  iota := %s' % str(P.iota))
        A('  pts := [%s]' % ', '.join(pts_lean(x) for x in P.pts))
        A('  ws := [%s]' % ', '.join(aff(w) for w in P.ws))
        A('  regs := [%s]' % (','+NL+'    ').join('{ lo := %s, hi := %s, sel := [%s] }' % (aff(a), aff(b), ', '.join('(%d, %d)' % t for t in sel)) for (a, b, sel) in g.regs))
        A('  cm := %s' % aff(P.cm))
        A('')
        A('def pdCov%d : CovData where' % k)
        A('  S0 := %d' % cov['S0'])
        A('  Jlo := %d' % cov['Jlo'])
        A('  Z := %d' % cov['Z'])
        A('  hiZ := [%s]' % (','+NL+'    ').join('[%s]' % (','+NL+'      ').join(zone_lean(z) for z in zs) for zs in cov['hiZ']))
        A('  loZ := [%s]' % (','+NL+'    ').join('[%s]' % (','+NL+'      ').join(zone_lean(z) for z in zs) for zs in cov['loZ']))
        A('  hiB := [%s]' % ', '.join('(%s, %s)' % (aff(a), aff(b)) for a, b in cov['hiB']))
        A('  loB := [%s]' % ', '.join('(%s, %s)' % (aff(a), aff(b)) for a, b in cov['loB']))
        A('  AT := [%s]' % (','+NL+'    ').join('[%s]' % ', '.join(str(x) for x in row) for row in cov['AT']))
        A('  BT := [%s]' % (','+NL+'    ').join('[%s]' % ', '.join(str(x) for x in row) for row in cov['BT']))
        A('')
        A('def pdCert%d : Cert := [%s]' % (k, (','+NL+'    ').join('(%s, [%s])' % (aff(f), ', '.join(step_lean(s) for s in prog)) for f, prog in g.M.cert.entries)))
        A('')
        A('def pd%d : PData := { m := pdMeta%d, cs := pdCert%d, cd := pdCov%d, ztop := %s }' % (k, k, k, k, 'true' if P.top_zero else 'false'))
        A('')
        M = 'pd%d' % k
        W = '(winOf %s.m)' % M
        A('theorem p%d_1 : decide (%s.m.pts.length = pk.charts.length) = true := by decide +kernel' % (k, M))
        A('theorem p%d_2 : decide (%s.m.pts.length = %s.m.ws.length) = true := by decide +kernel' % (k, M, M))
        A('theorem p%d_3 : decide (1 ≤ %s.m.ex) = true := by decide +kernel' % (k, M))
        A('theorem p%d_4 : %s.m.ws.all (fun f => holds %s %s.cs f) = true := by decide +kernel' % (k, M, W, M))
        A('theorem p%d_5 : holds %s %s.cs ⟨0, 2, -59⟩ = true := by decide +kernel' % (k, W, M))
        A('theorem p%d_6 : holds %s %s.cs %s.m.cm = true := by decide +kernel' % (k, W, M, M))
        A('theorem p%d_7 : holds %s %s.cs (pAff.sub %s.m.cm) = true := by decide +kernel' % (k, W, M, M))
        A('theorem p%d_8 : geomCheck %s.m %s %s.cs = true := by decide +kernel' % (k, M, W, M))
        A('theorem p%d_9 : hdomCheckG pk %s.m %s %s.cs %s.ztop = true := by decide +kernel' % (k, M, W, M, M))
        A('theorem p%d_10 : uniqCheck pk %s.m %s %s.cs = true := by decide +kernel' % (k, M, W, M))
        A('theorem p%d_11 : tOK pk %s.m %s %s.cs Pt.p1 [(1, 4 * %s.m.b + 2)] (pAff.sub rA) = true := by decide +kernel' % (k, M, W, M, M))
        A('theorem p%d_13 : ckOK %s.m.b %s.m.ex = true := by decide +kernel' % (k, M, M))
        A('theorem csc%d : coverScalar pk %s.m %s %s.cs %s.cd = true := by decide +kernel' % (k, M, W, M, M))
        # chunks of the cover
        n = g.P.n
        cost = lambda t: (len(cov['hiZ'][t]) + len(cov['loZ'][t]) + 1) * n
        chunks = []
        t = 0
        L_ = len(cov['hiZ'])
        while t < L_:
            c0 = t; acc = 0
            while t < L_ and (acc == 0 or acc + cost(t) <= 150):
                acc += cost(t); t += 1
            chunks.append((c0, t - c0))
        for i, (c0, ln) in enumerate(chunks):
            A("theorem cch%d_%d : (List.range' %d %d).all (sidesAt pk %s.m %s %s.cs %s.cd) = true := by decide +kernel" % (k, i, c0, ln, M, W, M, M))
        A('def chunks%d : List (ℕ × ℕ) := [%s]' % (k, ', '.join('(%d, %d)' % c for c in chunks)))
        A('theorem p%d_12 : coverCheck pk %s.m %s %s.cs %s.cd = true :=' % (k, M, W, M, M))
        A('  coverCheck_of_chunks pk %s.m %s %s.cs %s.cd csc%d chunks%d (by decide)' % (M, W, M, M, k, k))
        A('    (by simp only [chunksOK, chunks%d, List.all_cons, List.all_nil, Bool.and_true, %s])' % (k, ', '.join('cch%d_%d' % (k, i) for i in range(len(chunks)))))
        A('theorem check_ok%d : checkHost pk pd%d = true :=' % (k, k))
        A('  checkHost_of_parts pk pd%d p%d_1 p%d_2 p%d_3 p%d_4 p%d_5 p%d_6 p%d_7 p%d_8 p%d_9 p%d_10 p%d_11 p%d_12 p%d_13' % ((k,) * 14))
        A('')
        A('theorem hw_eq%d (g : Fin pk.charts.length) (N p : ℕ) : wNat g N p = wdOf pd%d.m N p g.val := by' % (k, k))
        A('  obtain ⟨g, hg⟩ := g')
        A('  rw [pk_len] at hg')
        A('  unfold wNat wdOf')
        A('  have h : ∀ k : Fin %d, ((wInt N p).getD k 0) = ((pdMeta%d.ws.getD k ⟨0, 0, 0⟩).eval (N : ℤ) (((p : ℤ) - 1) / 2)) := by' % (len(P.pts), k))
        A('    intro k')
        A('    fin_cases k <;> simp [wInt, pdMeta%d, Aff.eval] <;> try ring' % k)
        A('  exact congrArg Int.toNat (h ⟨g, hg⟩)')
        A('')
        A('theorem hc_eq%d (N p : ℕ) : cNat N p = cmN pd%d.m N p := by' % (k, k))
        # G8g 28 Oct: when `cNat` is written with all three coefficients (truncated-atom packets, e.g. L0076)
        # `simp only` already closes the goal ("No goals to be solved" at `congr 1`), so the rest runs under `<;>`.
        A('  unfold cNat cmN; simp only [pd%d, pdMeta%d, Aff.eval] <;> (congr 1; try ring)' % (k, k))
        A('')
    names = ['pd%d' % k for k in range(K)]
    A('def pds : List PData := [%s]' % ', '.join(names))
    A('')
    A('theorem win_cover (N p : ℕ) (h : Win N p) : ∃ pd ∈ pds, inWin pd.m N p := by')
    A('  obtain ⟨h1, h2, h3, h4⟩ := h')
    if K == 1:
        A('  exact ⟨pd0, by simp [pds], h1, h2, h3, h4⟩')
    else:
        A('  have key : %s := by' % ' ∨ '.join('inWin pdMeta%d N p' % k for k in range(K)))
        A('    simp only [inWin, %s]; omega' % ', '.join('pdMeta%d' % k for k in range(K)))
        pat = ' | '.join('k%d' % k for k in range(K))
        A('  rcases key with %s' % ' | '.join('k%d' % k for k in range(K)))
        for k in range(K):
            A('  · exact ⟨pd%d, by simp [pds], k%d⟩' % (k, k))
    A('')
    A('theorem phys : Phys :=')
    A('  physHost_of_checks pk pds pk_sound Win cNat wNat win_cover')
    A('    (fun pd hpd N p _ => by')
    A('      simp only [pds, List.mem_cons, List.not_mem_nil, or_false] at hpd')
    A('      rcases hpd with %s' % ' | '.join('rfl' for k in range(K)))
    for k in range(K):
        A('      · exact hc_eq%d N p' % k)
    A('    )')
    A('    (fun pd hpd g N p => by')
    A('      simp only [pds, List.mem_cons, List.not_mem_nil, or_false] at hpd')
    A('      rcases hpd with %s' % ' | '.join('rfl' for k in range(K)))
    for k in range(K):
        A('      · exact hw_eq%d g N p' % k)
    A('    )')
    A('    (fun pd hpd => by')
    A('      simp only [pds, List.mem_cons, List.not_mem_nil, or_false] at hpd')
    A('      rcases hpd with %s' % ' | '.join('rfl' for k in range(K)))
    for k in range(K):
        A('      · exact check_ok%d' % k)
    A('    )')
    A('')
    A('end')
    A('end CatalanMeasure.GenD.Uniform.Bank532.Pk.%s' % nm)
    open(out, 'w', encoding='utf-8').write(NL.join(L) + NL)
    return g0, res0

if __name__ == '__main__' and len(sys.argv) >= 3:
    g, res = emit(sys.argv[1], sys.argv[2])
    print('emitted', sys.argv[2], res)
