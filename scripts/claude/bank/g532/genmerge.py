"""G10: generate Bank532/Ledger{B}.lean (merged ledger on top of wins13) + Final{B}.lean for rung B in {534,533,532}.
usage: genmerge.py B   (needs final532.json from genall.py, sel532.json for the gap order)"""
import os, sys; sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import json, re
sys.dont_write_bytecode = True
from fractions import Fraction as F
import profile13 as P, merge as M
D = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(D, '../../../..'))
OUT = ROOT + '/CatalanMeasure/GenD/Uniform/Bank532/'
B = int(sys.argv[1])
NEED = {534: F(2194225, 100000), 533: F(2200225, 100000), 532: F(2205325, 100000)}[B]
ETA = {534: '2993 / 100', 533: '2999 / 100', 532: '30041 / 1000'}[B]
NPK = {534: 1, 533: 4, 532: 10 ** 6}[B]
sel = json.load(open(D + '/sel532.json'))          # [gap, key, a, b, c0, c1] sorted by gap
final = json.load(open(D + '/final532.json'))      # key -> windows after margin fitting
final['D58-L0146|k152_25'] = [['6', '152/25', '73', '-12']]
keys = []
for g, k, *_ in sel:
    if k not in keys: keys.append(k)
keys = keys[:NPK]
def nm(k): return re.sub(r'[^A-Za-z0-9_]', '_', k.replace('D58-', '').replace('|', '_'))
def rl(x):
    x = F(x); return '(%d : ℝ)' % x.numerator if x.denominator == 1 else '(%d / %d : ℝ)' % (x.numerator, x.denominator)
W = P.load()
old = [(a, b, c0, c1, ('old', i)) for i, (a, b, c0, c1) in enumerate(W)]
new = []
for k in keys:
    if k not in final: print('missing', k); continue
    for wi, w in enumerate(final[k]):
        a, b, c0, c1 = (F(x) for x in w); new.append((a, b, c0, c1, ('new', k, wi)))
usedkeys = []
for w in new:
    if w[4][1] not in usedkeys: usedkeys.append(w[4][1])
E = M.envelope(old, new)
keysE = [k for k in usedkeys if any(w[4][0] == 'new' and w[4][1] == k for w in E)]
# parents: new windows full
newfull = {(w[4][1], w[4][2]): w for w in new}
oldfull = {w[4][1]: w for w in old}
gain = sum(M.area(w) for w in E)
print('rung', B, 'packets', len(keysE), 'windows', len(E), 'gain', float(gain), 'need', float(NEED), 'margin', float(gain - NEED))
assert gain >= NEED
# ---------------- Lean
ns = 'CatalanMeasure.GenD.Uniform.Bank532'
imports = ['CatalanMeasure.GenD.Uniform.Bank532.MergeUtil', 'CatalanMeasure.GenD.Uniform.Bank532.Gate',
           'CatalanMeasure.GenD.Uniform.Bank540.Ledger5.Final5'] + ['%s.Pk.%s' % (ns, nm(k)) for k in keysE]
L = ['module', ''] + ['public import ' + i for i in imports] + ['', '@[expose] public section', 'set_option Elab.async false', '',
     '/-! Merged ledger for `B = %d` on top of `wins13` (generated by scripts/claude/bank/g532/genmerge.py).' % B,
     '    Windows: pointwise envelope of `W13` and the packet windows of %d packets.  Each packet host `phys` is a field of `Hosts%d`. -/' % (len(keysE), B), '',
     'namespace %s' % ns,
     'open CatalanMeasure.GenD D58 Filter CatalanMeasure.Parametric OAI.InternalCatalan',
     'open CatalanMeasure.GenD.Uniform.LedgerW CatalanMeasure.GenD.Uniform.Arithmetic',
     'open CatalanMeasure.GenD.Uniform.Bank540.Ledger CatalanMeasure.GenD.Uniform.Bank540.Ledger3 CatalanMeasure.GenD.Uniform.Bank540.Ledger4',
     'open CatalanMeasure.GenD.Uniform.Bank535.Ledger10 CatalanMeasure.GenD.Uniform.W.Prof CatalanMeasure.GenD.Uniform.W.Charts3',
     'noncomputable section', '']
L.append('structure Hosts%d : Prop where' % B)
for k in keysE: L.append('  h_%s : Pk.%s.Phys' % (nm(k), nm(k)))
L.append('')
def lbexpr(k): return 'NullityLB.ofPacketHost adm Pk.%s.pk Pk.%s.pk_sound Pk.%s.Win Pk.%s.cNat Pk.%s.wNat%s H.h_%s' % (nm(k), nm(k), nm(k), nm(k), nm(k), 'O' if k.startswith('D58-L0146') else '', nm(k))
def lbexpr(k):
    n = nm(k)
    if k.startswith('D58-L0146'):
        return 'NullityLB.ofPacketHost adm CatalanMeasure.GenD.Uniform.W.Charts4.Pilot146O.packetO CatalanMeasure.GenD.Uniform.W.Charts4.Pilot146O.packetO_sound CatalanMeasure.GenD.Uniform.W.Charts4.Win CatalanMeasure.GenD.Uniform.W.Charts4.cNat CatalanMeasure.GenD.Uniform.W.Charts4.Pilot146O.wNatO H.h_%s' % n
    return 'NullityLB.ofPacketHost adm Pk.%s.pk Pk.%s.pk_sound Pk.%s.Win Pk.%s.cNat Pk.%s.wNat H.h_%s' % (n, n, n, n, n, n)
for k in keysE: L.append('def lb_%s (H : Hosts%d) : NullityLB design := %s' % (nm(k), B, lbexpr(k)))
L.append('')
L.append('def fams%d (H : Hosts%d) : List (NullityLB design) :=\n  fams13 ++ [%s]' % (B, B, ', '.join('lb_%s H' % nm(k) for k in keysE)))
L.append('')
L.append('def wins%d : List KapWindow :=\n  [%s]' % (B, ',\n   '.join('cw %s %s %s %s' % tuple(rl(x) for x in w[:4]) for w in E)))
L.append('')
n = len(E)
cases = ' | '.join(['rfl'] * n)
L.append('theorem wins%d_pos : ∀ w ∈ wins%d, 0 < w.a ∧ w.a < w.b ∧ w.b ≤ 78 := by' % (B, B))
L += ['  intro w hw', '  simp only [wins%d, List.mem_cons, List.not_mem_nil, or_false] at hw' % B, '  rcases hw with %s <;> simp only [cw] <;> norm_num' % cases, '']
L.append('theorem wins%d_rec : ∀ w ∈ wins%d, w.b ≤ 1 ∨ 2 ≤ w.a := by' % (B, B))
L += ['  intro w hw', '  simp only [wins%d, List.mem_cons, List.not_mem_nil, or_false] at hw' % B, '  rcases hw with %s <;> simp only [cw] <;> norm_num' % cases, '']
L.append('theorem wins%d_chain : Chain wins%d := by' % (B, B))
L += ['  simp only [wins%d, Chain, cw]' % B, '  norm_num', '']
L.append('theorem wins%d_ord : wins%d.Pairwise (fun s t => s.b ≤ t.a) :=' % (B, B))
L += ['  chain_pairwise _ (by', '    intro w hw', '    simp only [wins%d, List.mem_cons, List.not_mem_nil, or_false] at hw' % B,
      '    rcases hw with %s <;> simp only [cw] <;> norm_num) wins%d_chain' % (cases, B), '']
L.append('def gain%d : ℝ := (wins%d.map (KapWindow.area 58)).sum' % (B, B))
L.append('')
L.append('theorem gain%d_ge : (%s : ℝ) ≤ gain%d := by' % (B, {534: '2194225 / 100000', 533: '2200225 / 100000', 532: '2205325 / 100000'}[B], B))
L += ['  unfold gain%d wins%d' % (B, B), '  simp only [List.map_cons, List.map_nil, List.sum_cons, List.sum_nil, cw_area]', '  norm_num', '']
# cert
L.append('theorem wins%d_cert (H : Hosts%d) : ∀ w ∈ wins%d, ∃ lb ∈ fams%d H, WinCert lb w := by' % (B, B, B, B))
L += ['  intro w hw', '  simp only [wins%d, List.mem_cons, List.not_mem_nil, or_false] at hw' % B, '  rcases hw with %s' % cases]
for w in E:
    a, b, c0, c1, tag = w
    if tag[0] == 'old':
        pa, pb, pc0, pc1, _ = oldfull[tag[1]]
        L.append('  · obtain ⟨lb, hl, hc⟩ := old_cert (k := %d) (a := %s) (b := %s) (c0 := %s) (c1 := %s) (a\' := %s) (b\' := %s) rfl (by norm_num) (by norm_num)'
                 % (tag[1], rl(pa), rl(pb), rl(pc0), rl(pc1), rl(a), rl(b)))
        L.append('    exact ⟨lb, List.mem_append_left _ hl, hc⟩')
    else:
        k, wi = tag[1], tag[2]
        pa, pb, pc0, pc1, _ = newfull[(k, wi)]
        n_ = nm(k)
        L.append('  · exact ⟨lb_%s H, List.mem_append_right _ (by simp), WinCert.shrink (Pk.%s.win%d adm H.h_%s) (by norm_num) (by norm_num)⟩' % (n_, n_, wi, n_))
L.append('')
L.append('theorem partial_growth%d (H : Hosts%d) {ε : ℝ} (hε : 0 < ε) :' % (B, B))
L += ['    ∀ᶠ N : ℕ in atTop,', '      Real.log (((canonicalNormalizer design D58.Odd.design_admissible (famLB (fams%d H)) 79' % B,
      '        (by rw [D58.Odd.design_H]; norm_num)).D N : ℕ) : ℝ) ≤',
      '        (24733 / 4 + 2673 / 8 * Real.log 2 - gain%d + ε) * (N : ℝ) ^ 2 :=' % B,
      '  growth_of_families (fams%d H) wins%d gain%d rfl wins%d_pos wins%d_ord wins%d_rec (wins%d_cert H) hε' % (B, B, B, B, B, B, B), '',
      'end', 'end ' + ns, '#print axioms %s.wins%d_chain' % (ns, B), '#print axioms %s.wins%d_ord' % (ns, B), '#print axioms %s.gain%d_ge' % (ns, B), '#print axioms %s.wins%d_cert' % (ns, B), '#print axioms %s.partial_growth%d' % (ns, B)]
open(OUT + 'Ledger%d.lean' % B, 'w', encoding='utf-8').write('\n'.join(L) + '\n')
# ---------------- Final
F_ = ['module', '', 'public import %s.Ledger%d' % (ns, B), '', '@[expose] public section', 'set_option Elab.async false', '',
      '/-! `μ(G) ≤ %d`, conditional on the packet hosts `Hosts%d` (G8d supplies them). -/' % (B, B), '',
      'namespace %s' % ns,
      'open CatalanMeasure.GenD Filter CatalanMeasure.Parametric OAI.InternalCatalan',
      'open CatalanMeasure.GenD.Uniform.Arithmetic CatalanMeasure.GenD.Uniform.Bank540.Ledger',
      'open CatalanMeasure.GenD.Uniform.Bank540.Ledger3 CatalanMeasure.GenD.Uniform.Bank535',
      'noncomputable section', '',
      '/-- **`μ(G) ≤ %d`** given the physical hosts of the %d packets. -/' % (B, len(keysE)),
      'theorem catalan_irrationalityMeasure_%d_of_hosts (H : Hosts%d) :' % (B, B),
      '    ∀ᶠ b : ℕ in atTop, ∀ a : ℤ,',
      '      (b : ℝ) ^ (-(%d : ℝ)) <' % B,
      '        |(∑\' j : ℕ, (-1 : ℝ) ^ j / ((2 * j + 1 : ℕ) : ℝ) ^ 2) - a / b| := by',
      '  have h := measure_of_design D58.Odd.design',
      '    { B := %d' % B,
      '      Z := canonicalNormalizer design D58.Odd.design_admissible (famLB (fams%d H)) 79' % B,
      '        (by rw [D58.Odd.design_H]; norm_num)',
      '      w := 3 / 4, ρ := Bank540.rho, η := %s, κ := %d / Bank540.rho, δ := D58.delta' % (ETA, B),
      '      pay := by', '        rw [D58.n0_sub_g0]', '        simpa [payB] using pay%d' % B,
      '      gD := gDg gain%d' % B,
      '      D_growth := fun ε hε => by',
      '        filter_upwards [partial_growth%d H hε] with N hN' % B,
      '        unfold gDg', '        convert hN using 2',
      '      tΔ := Bank540.tDelta', '      delta_small := Bank540.delta_small',
      '      eta_le := gain_ok%d _ gain%d_ge' % (B, B),
      '      nonvanishing := D58.nonvanishing_d58 D58.C3.c3_d58 }',
      '  simpa [catalan] using h', '', 'end', 'end ' + ns,
      '#print axioms %s.catalan_irrationalityMeasure_%d_of_hosts' % (ns, B)]
open(OUT + 'Final%d.lean' % B, 'w', encoding='utf-8').write('\n'.join(F_) + '\n')
print('wrote Ledger/Final', B, 'packets', keysE)
