def chunk(name,items,start):
    """items: list of (s,t,Line)"""
    rows=[]; mass=F(0)
    for (s,t,ln) in items:
        sn,sd,tn,td,A,B,E,D=G.piece_args(s,t,ln)
        rows.append(f'  mkPiece {sn} {sd} {tn} {td} {G.par(A)} {G.par(B)} {G.par(E)} {D}')
        mass+=mass_piece(s,t,ln)
    end=items[-1][1]
    txt=HDR+f'noncomputable def {name} : List Piece := [\n'+',\n'.join(rows)+']\n\n'
    txt+=f'def {name}Mass : ℚ := {q(mass)}\n\n'
    txt+=f'theorem {name}_chain : Chain {q(start)} {name} := by\n  norm_num [{name}, Chain, mkPiece]\n\n'
    txt+=f'theorem {name}_end : lastEnd {q(start)} {name} = {q(end)} := by\n  norm_num [{name}, lastEnd, mkPiece]\n\n'
    txt+=f'theorem {name}_mass : listInt {name} = ({name}Mass : ℝ) := by\n  norm_num [{name}, listInt, Piece.int, mkPiece, {name}Mass]\n\n'
    txt+='end CatalanCore.Uniform.Bank.ThirdsContent\n'
    open(OUT+name+'.lean','w',encoding='utf-8').write(txt)
    return mass,end
