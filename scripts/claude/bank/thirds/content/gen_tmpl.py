# ------------------------------------------------ R/LP interface lists and dispatch
ROOT_OF={(1,1):0,(1,5):1,(2,1):1,(2,5):0}
def rlp_file():
    txt=HDR.replace('a chunk of the finite no-UF template','the rank/LP pieces (the part of the template not covered by the tropical, M3D and prefix lemmas)')
    for (a,cls),root in ROOT_OF.items():
        rows=[]
        for k,p in enumerate(G.prof['classes'][root]['pieces']):
            if p['layer'] in ('R','LP'):
                s,t=F(p['left']),F(p['right']); ln=G.Line(*map(F,p['line']))
                sn,sd,tn,td,A,B,E,D=G.piece_args(s,t,ln)
                rows.append(f'  mkPiece {sn} {sd} {tn} {td} {G.par(A)} {G.par(B)} {G.par(E)} {D}')
        txt+=f'noncomputable def rlpList_{a}_{cls} : List Piece := [\n'+',\n'.join(rows)+']\n\n'
    txt+='end CatalanCore.Uniform.Bank.ThirdsContent\n'
    open(OUT+'RLP.lean','w',encoding='utf-8').write(txt)
rlp_file()

