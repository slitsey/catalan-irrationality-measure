def lean_form(D):
    q, al = D['q'], D['al']
    out = {}
    for j, (t1, pcs) in D['tmpls'].items():
        ka = F(j, q)
        rows = []
        for P, (bi, cuts, strips) in pcs:
            ok, Rr, need = X.piece_ok(P, (bi, cuts, strips), D['cat'], q, al, ka, D['depth'], D['cF'], D['Pbad'])
            assert ok
            conds = D['cat'][bi][1]
            st2 = [(left, yi, w, X.strip_V(conds, al, ka, q, P[0] if left else P[1])) for left, yi, w in strips]
            cert = (bi, list(cuts), st2, Rr)
            assert X.piece_ok_lean(P, cert, D['cat'], q, al, ka, D['depth'], D['cF'], D['Pbad']), (j, P)
            rows.append((P, cert))
        out[j] = (t1, rows)
    return out


def unit_check(D, T):
    for a in D['members']:
        tot, cnt = F(0), 0
        for c in range(D['M']):
            if math.gcd(D['M'], c) != 1:
                continue
            cnt += 1
            jj = X.jOf(D['q'], a, c)
            assert jj is not None and jj in T
            t1, rows = T[jj]
            tot += D['alpha0'] * t1 + sum(P[2] * (P[1] - P[0]) + P[3] * (P[1] * P[1] - P[0] * P[0]) / 2
                                          for P, _ in rows)
        assert tot == D['Lam'] * cnt, (a, tot / cnt, D['Lam'])


def lq(x):
    x = F(x)
    return f'(qq ({x.numerator}) {x.denominator})'


def lcert(cert):
    bi, cuts, strips, Rr = cert
    cs = ', '.join(lq(x) for x in cuts)
    ss = ', '.join('⟨%s, %d, %s, %s⟩' % ('true' if l else 'false', yi, lq(w), lq(V)) for l, yi, w, V in strips)
    return f'⟨{bi}, [{cs}], [{ss}], {lq(Rr)}⟩'


def nest(names):
    """a ++ (b ++ (c ++ d)) as written by List.append right-association."""
    return ' ++ ('.join(names) + ')' * (len(names) - 1)


