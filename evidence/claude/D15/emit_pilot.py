"""Emit CatalanCore/Uniform/Decay/FarField/PilotData.lean from pilot_mu.txt / pilot_cells.json
(produced by gen_pilot.py).  Run: python -I -X utf8 evidence/claude/D15/emit_pilot.py"""
import json
from fractions import Fraction as Fr

mu = open('evidence/claude/D15/pilot_mu.txt').read()
cells = json.load(open('evidence/claude/D15/pilot_cells.json'))


def qs(s):
    f = Fr(s)
    return "(%d / %d : ℚ)" % (f.numerator, f.denominator)


toks = mu.split(', ')
rows = [", ".join(toks[i:i + 4]) for i in range(0, len(toks), 4)]
tape = ",\n    ".join(rows)
cdefs = "\n\n".join(
    "def fc%d : TCell3 := ⟨%s, %s, .mp (%s) (%s)⟩" % (i, qs(a), qs(b), qs(rm), qs(rh))
    for i, (a, b, rm, rh) in enumerate(cells))

src = """import CatalanCore.Uniform.Bank.Chi3.Env
import CatalanCore.Uniform.Decay.FarField.Top3
set_option Elab.async false
set_option maxRecDepth 100000

/-! Generated by evidence/claude/D15/emit_pilot.py (lane D, D15): far-field pilot data for the
chi3 tube edge 7 (centre 1/2, R = 1, K = 24, J = 8). -/

namespace CatalanCore.Uniform.Bank.Chi3.FarPilot
open CatalanCore.Uniform.Decay.Cert CatalanCore.Uniform.Decay.PolyWire CatalanCore.Uniform.Decay.PolyWire2
  CatalanCore.Uniform.Decay.PolyCells CatalanCore.Uniform.Decay.Polygon CatalanCore.Uniform.Decay.Cells
  CatalanCore.Uniform.Decay.NearCells CatalanCore.Uniform.Decay.PolyFull
  CatalanCore.Uniform.Decay.FarField

def cqsOf : List ℤ → List CQ
  | a :: b :: c :: d :: t => ⟨qOfP a b, qOfP c d⟩ :: cqsOf t
  | _ => []

/-- The claimed moments `μ_1, ..., μ_24` of the chi3 trial measure about `1/2`. -/
def muC : List CQ := cqsOf raw_ints% [
    @TAPE@]

def Mfar : MPData := ⟨⟨1 / 2, 0⟩, 1, 24, 8, 5 / 2, muC⟩

/-- The two far-field cells replacing all 93 cells of edge 7. -/
@CDEFS@

def farE7 : List TCell3 := [fc0, fc1]

end CatalanCore.Uniform.Bank.Chi3.FarPilot
""".replace("@TAPE@", tape).replace("@CDEFS@", cdefs)
open('CatalanCore/Uniform/Decay/FarField/PilotData.lean', 'w', encoding='utf-8').write(src)
print(len(src))
